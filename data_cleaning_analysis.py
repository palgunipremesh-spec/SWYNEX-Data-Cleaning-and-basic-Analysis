# Importing required libraries

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

print("All libraries imported successfully!")

# Downloading GSE10072 biological dataset from NCBI GEO

import requests

url = "https://ftp.ncbi.nlm.nih.gov/geo/series/GSE10nnn/GSE10072/matrix/GSE10072_series_matrix.txt.gz"

response = requests.get(url)

print("Download status:", response.status_code)

print("File size:", len(response.content), "bytes")

# Saving the downloaded GSE10072 dataset

with open("GSE10072_series_matrix.txt.gz", "wb") as file:
    file.write(response.content)

print("GSE10072 dataset saved successfully!")

# Reading the downloaded dataset

import gzip
from io import StringIO

with gzip.open(
    "GSE10072_series_matrix.txt.gz",
    "rt",
    encoding="utf-8"
) as file:

    lines = file.readlines()

print("Dataset file opened successfully!")

# Step 6: Convert GEO data into a Pandas DataFrame

from io import StringIO

# Find the beginning of the expression table
start = next(
    i for i, line in enumerate(lines)
    if line.strip() == "!series_matrix_table_begin"
)

# Find the end of the expression table
end = next(
    i for i, line in enumerate(lines)
    if line.strip() == "!series_matrix_table_end"
)

# Extract the actual table
table_text = "".join(lines[start + 1:end])

# Convert text into a Pandas DataFrame
data = pd.read_csv(
    StringIO(table_text),
    sep="\t"
)

# Display the results
print("Dataset loaded successfully!")
print("Number of rows and columns:", data.shape)

display(data.head())

# Initial Data Inspection

print("DATASET INFORMATION")
print("-------------------")

# Dataset dimensions
print("Rows and columns:", data.shape)

# Check column names
print("\nColumn names:")
print(data.columns.tolist())

# Check data types
print("\nData types:")
print(data.dtypes.value_counts())

# Check missing values
print("\nTotal missing values:")
print(data.isnull().sum().sum())

# Check duplicate probe IDs
print("\nDuplicate probe IDs:")
print(data["ID_REF"].duplicated().sum())

# Display basic information
print("\nDataset information:")
data.info()

# Step 8: Basic Statistical Analysis

# Select only numerical gene-expression columns
expression_data = data.drop(columns=["ID_REF"])

# Calculate descriptive statistics
statistics = expression_data.describe()

# Display the results
print("BASIC STATISTICAL SUMMARY")
display(statistics)

# Step 9: Gene Expression Distribution

plt.figure(figsize=(10, 5))

plt.hist(
    expression_data.values.flatten(),
    bins=50
)

plt.title("Distribution of Gene Expression Values")
plt.xlabel("Gene Expression Values")
plt.ylabel("Frequency")

plt.show()

# Step 11: Inspect sample information

import csv

# Extract sample accession numbers
geo_line = next(
    line for line in lines
    if line.startswith("!Sample_geo_accession")
)

# Extract sample titles
title_line = next(
    line for line in lines
    if line.startswith("!Sample_title")
)

accessions = next(csv.reader([geo_line], delimiter="\t"))
titles = next(csv.reader([title_line], delimiter="\t"))

# Display sample information
print("SAMPLE INFORMATION")
print("------------------")

for accession, title in zip(accessions[1:], titles[1:]):
    print(accession, ":", title)

# Step 12: Separate Tumor and Normal samples

import pandas as pd

# Create sample information table
sample_info = pd.DataFrame({
    "GSM": accessions[1:],
    "Title": titles[1:]
})

# Identify tumor samples
tumor_samples = sample_info[
    sample_info["Title"].str.contains(
        "Lung Tumor", case=False, na=False
    )
]["GSM"].tolist()

# Identify normal lung samples
normal_samples = sample_info[
    sample_info["Title"].str.contains(
        "Normal Lung", case=False, na=False
    )
]["GSM"].tolist()

# Separate expression data
tumor_data = data[["ID_REF"] + tumor_samples].copy()

normal_data = data[["ID_REF"] + normal_samples].copy()

# Display results
print("TUMOR AND NORMAL SAMPLE SEPARATION")
print("----------------------------------")

print("Number of tumor samples:", len(tumor_samples))
print("Number of normal samples:", len(normal_samples))

print("\nTumor dataset shape:", tumor_data.shape)
print("Normal dataset shape:", normal_data.shape)

print("\nTumor sample names:")
print(tumor_samples)

print("\nNormal sample names:")
print(normal_samples)

# Step 13: Calculate average expression

# Calculate mean expression for tumor samples
tumor_mean = tumor_data.drop(
    columns=["ID_REF"]
).mean(axis=1)

# Calculate mean expression for normal samples
normal_mean = normal_data.drop(
    columns=["ID_REF"]
).mean(axis=1)

# Create a comparison table
comparison = pd.DataFrame({
    "Probe_ID": data["ID_REF"],
    "Tumor_Mean": tumor_mean,
    "Normal_Mean": normal_mean
})

# Calculate difference
comparison["Difference"] = (
    comparison["Tumor_Mean"] -
    comparison["Normal_Mean"]
)

# Display results
print("AVERAGE GENE EXPRESSION COMPARISON")

display(comparison.head(10))

# Step 14: Visual comparison of gene expression

# Find the 10 probes with the largest differences
top10 = comparison.loc[
    comparison["Difference"].abs().nlargest(10).index
].copy()

# Create graph
plt.figure(figsize=(12, 6))

x = np.arange(len(top10))
width = 0.35

plt.bar(
    x - width/2,
    top10["Tumor_Mean"],
    width,
    label="Tumor"
)

plt.bar(
    x + width/2,
    top10["Normal_Mean"],
    width,
    label="Normal"
)

plt.xticks(
    x,
    top10["Probe_ID"],
    rotation=45,
    ha="right"
)

plt.xlabel("Probe IDs")
plt.ylabel("Average Expression")
plt.title("Tumor vs Normal Gene Expression")
plt.legend()
plt.tight_layout()
plt.show()

# Step 15: Save analysis results

# Save complete comparison table
comparison.to_csv(
    "GSE10072_Expression_Comparison.csv",
    index=False
)

# Save top 10 probes
top10.to_csv(
    "GSE10072_Top10_Probes.csv",
    index=False
)

